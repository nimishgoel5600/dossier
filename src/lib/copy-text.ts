// Copies text to the clipboard.

/**
 * Copies `text`, resolving to whether it worked. The Clipboard API only
 * exists on HTTPS and localhost, so a server reached over plain HTTP gets
 * the older copy command instead.
 */
export async function copyText(text: string): Promise<boolean> {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Refused, e.g. without focus: try the older way.
    }
  }
  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.opacity = "0";
  document.body.append(area);
  area.select();
  try {
    return document.execCommand("copy");
  } catch {
    return false;
  } finally {
    area.remove();
  }
}
